import fs from 'node:fs/promises';
import path from 'node:path';

const root=path.resolve('public/assets');
const output=path.resolve('src/asset-sizes.generated.js');
const sizes={};

async function scan(directory){
 for(const entry of await fs.readdir(directory,{withFileTypes:true})){
  const absolute=path.join(directory,entry.name);
  if(entry.isDirectory())await scan(absolute);
  else if(entry.isFile()){
   const relative=path.relative(root,absolute).split(path.sep).join('/');
   sizes[relative]=(await fs.stat(absolute)).size;
  }
 }
}

await scan(root);
const ordered=Object.fromEntries(Object.entries(sizes).sort(([a],[b])=>a.localeCompare(b)));
await fs.writeFile(output,`// Generated by scripts/generate-asset-sizes.mjs.\nexport const ASSET_SIZES=${JSON.stringify(ordered)};\n`);
console.log(`Recorded ${Object.keys(ordered).length} asset sizes in ${path.relative(process.cwd(),output)}.`);
